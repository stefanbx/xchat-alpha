def accept_revocation(m):
    # Verified against the PINNED ROOT account only. Without a root pinned nothing is ever accepted, so
    # a hostile relay cannot invent a revocation to block legitimate updates (a denial-of-update attack).
    if not ROOT_ACCT or xc is None or not isinstance(m, dict):
        return False
    acct, succ = m.get('revoked', ''), m.get('successor', '')
    pub, sig, ts = m.get('pub', ''), m.get('sig', ''), m.get('ts', 0)
    if not acct or not pub or not sig:
        return False
    try:
        if xc.pub_to_addr(pub) != ROOT_ACCT:
            return False
        if not xc.verify_msg(pub, xc.sig_canon('revocation', acct, succ, ts), sig):
            return False
    except Exception:
        return False
    cur = revocations.get(acct)
    if cur and int(cur.get('ts', 0)) >= int(ts or 0):
        return False
    revocations[acct] = m
    mark_dirty()
    return True

