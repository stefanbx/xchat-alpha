def _dm_key(m):
    # Dedup key for a stored DM. A SEALED-SENDER record (v2) hides `from`, so the old (from, ts) key
    # would collapse every sealed record to (None, ts) — two senders in the same second would lose a
    # message. A v2 record therefore carries its own random `mid`, and we key on that when present.
    # Legacy (v1) records keep the (from, ts) key unchanged, so this is additive: old records dedup
    # exactly as before, new records dedup on an id that does not depend on a visible sender.
    mid = m.get('mid')
    return ('mid', mid) if mid else ('ft', m.get('from'), m.get('ts'))

# Reading a mailbox: prove you own it.
#
# /dm returns records whose BODIES are sealed but whose `to`, `from` and `ts` are not, so serving
# them to anyone publishes the account's whole social graph. See the audit in
# docs/PRIVACY-AND-DECENTRALIZATION.md.
#
# STRICT IS OFF BY DEFAULT, on purpose, and it is the uncomfortable part of this change. Clients up
# to and including 2.5.0 do not sign these reads, so a relay that enforced today would break DMs for
# every install that exists right now — shipping a privacy fix by taking the feature away. So: the
# signature is accepted and verified whenever it is offered, the app and node send it from this
# version on, and an operator flips XC_DM_STRICT=1 once the people using their relay have updated.
# The default flips in a later release, when that is true by default rather than by hope.
#
# Until then this closes nothing on its own. It is the half that can ship without a flag day.
DM_STRICT = os.environ.get('XC_DM_STRICT', '0') == '1'
DM_SIG_WINDOW = int(os.environ.get('XC_DM_SIG_WINDOW', '300'))   # seconds either side of now

def _mailbox_ok(acc, q):
    """(allowed, reason). A valid signature always wins; an absent one depends on DM_STRICT."""
    if not acc:
        return False, 'account required'
    sig, pub, ts = q.get('sig', ''), q.get('pub', ''), q.get('ts', '')
    if not (sig and pub and ts):
        return (not DM_STRICT), 'this relay requires a signed mailbox read — update your app'
    try:
        ts_i = int(ts)
    except ValueError:
        return False, 'bad ts'
    # A captured signature is a bearer token for this mailbox, so bound how long it is worth
    # capturing. Both directions: a clock ahead of ours must not mint a token valid for hours.
    if abs(time.time() - ts_i) > DM_SIG_WINDOW:
        return False, 'signature expired'
    try:
        if xc.pub_to_addr(pub) != acc:
            return False, 'key does not match the account'
        if not xc.verify_msg(pub, xc.sig_canon('dminbox', acc, ts_i), sig):
            return False, 'bad signature'
    except Exception:
        return False, 'bad signature'
    return True, ''

_dirty = False                                                # state changed since the last flush
def mark_dirty():
    global _dirty
    _dirty = True

_rate = {}                                                    # client-ip -> [window_start, count]
_rate_lock = threading.Lock()
def rate_ok(ip):                                              # fixed-window per-IP write throttle
    now = time.time()
    with _rate_lock:
        w = _rate.get(ip)
        if not w or now - w[0] >= RATE_WINDOW:
            if ip not in _rate and len(_rate) >= RATE_ACCTS:
                _rate.pop(next(iter(_rate)), None)   # backstop: bound the number of tracked buckets
            _rate[ip] = [now, 1]; return True
        if w[1] >= RATE_MAX:
            return False
        w[1] += 1; return True

# --- content cache: a relay is a CACHE, not an archive, and blobs live on DISK ---
# Media blobs are held in an embedded SQLite table (not RAM, not the JSON store), so the relay's
# memory stays small and the cache can be as large as the disk, and writes are INCREMENTAL (one row
# per put/evict) instead of re-serialising the whole state every few seconds. A byte cap + eviction
# still apply: keep everything until full, then drop the LEAST-VALUABLE unpinned blobs first —
# untipped before tipped, least-recently-used within a level. Pay-to-pin protects a CID until paid.
BLOB_CAP = int(float(os.environ.get('XC_BLOB_CAP_MB', '512')) * 1024 * 1024)   # disk cache ceiling
PIN_DAYS_PER_XNO = float(os.environ.get('XC_PIN_DAYS_PER_XNO', '30000'))       # 0.001 XNO ≈ 30 days pinned
_PIN_S_PER_RAW = PIN_DAYS_PER_XNO * 86400.0 / 1e30
pinned = {}                          # cid -> pin-expiry epoch (paid); survives eviction until then
pins_paid = {}                       # payment block hash -> cid (consumed once; audit + no double-claim)
blob_meta = {}                       # cid -> {'size','last','tips','reports'} — small RAM eviction index

# Moderation as a NEGATIVE value signal. A signed community report cancels some of a post's tip-value,
# so ONE score — tips minus reports — ranks EVERYTHING: eviction (low score drops first), sync-the-best
# (high score replicates first; reported content isn't propagated), and a hard takedown once distinct
# reporters cross the threshold (the media is deleted; the post drops from the feed for everyone).
REPORT_WEIGHT   = float(os.environ.get('XC_REPORT_WEIGHT', '0.05'))   # XNO-equiv value one rep-unit cancels
TAKEDOWN_WEIGHT = float(os.environ.get('XC_TAKEDOWN_WEIGHT', '2'))    # reputation-weighted reporters -> drop
REPORT_POSTS    = int(os.environ.get('XC_REPORT_POSTS', '50000'))     # cap distinct reported posts
REPORT_PER_POST = int(os.environ.get('XC_REPORT_PER_POST', '1000'))   # cap reporters stored per post
_blob_reporters = {}                 # cid -> {account: reputation} (dedupe + weight; rebuilt on load)

def blob_score(m):                   # the universal value: tips earned minus the reputation-weighted penalty
    return float(m.get('tips', 0.0)) - float(m.get('reports', 0.0)) * REPORT_WEIGHT

_DB = os.path.join(os.path.dirname(os.path.abspath(STORE)) or '.', 'blobs.db')
_db = sqlite3.connect(_DB, check_same_thread=False)
_db.execute('PRAGMA journal_mode=WAL')
# A relay is a CACHE, not an archive. In WAL mode synchronous=NORMAL is CORRUPTION-SAFE (the db can't
# be damaged by a crash); the only cost of a power-loss is possibly losing the last committed blob
# write — harmless here, since blobs are content-addressed (re-fetchable from peers) and the head/JSON
# state lives in a SEPARATE file. In return we drop an fsync off every put/evict. Worth it at scale.
_db.execute('PRAGMA synchronous=NORMAL')
_db.execute('CREATE TABLE IF NOT EXISTS blob (cid TEXT PRIMARY KEY, b64 TEXT NOT NULL, '
            'size INTEGER, last REAL, tips REAL)')
_db.commit()
_blob_lock = threading.Lock()        # serialises all SQLite access (fine at relay throughput)

def _blob_total():
    return sum(m['size'] for m in blob_meta.values())

def blob_get(cid):                   # serve content from disk
    with _blob_lock:
        r = _db.execute('SELECT b64 FROM blob WHERE cid=?', (cid,)).fetchone()
    return r[0] if r else None

def blob_has(cid):
    return cid in blob_meta

def blob_put(cid, b64):
    # Reject an oversized blob BEFORE it is written. Two bugs this closes: (1) no per-blob ceiling let a
    # single huge upload fill the disk; (2) a blob larger than BLOB_CAP, stored first and evicted after,
    # sorted itself last (fresh + untipped) and so evicted EVERY other blob to get under cap while
    # surviving — one POST wiped the whole cache. With a per-blob cap << BLOB_CAP that can't happen.
    if not cid or not b64 or len(b64) > MAX_BLOB:
        return False
    with _blob_lock:
        now = time.time()
        # VALUE IS NEVER SELF-ASSERTED. This used to take a caller-supplied `tips` and ratchet the
        # blob's score up to it — but /blob is unauthenticated, so anyone could declare their own spam
        # the most valuable content on the relay and make it un-evictable while real content was
        # dropped to make room (blob_score ranks eviction AND sync priority). Value now only ever
        # arrives through blob_credit(), backed by a confirmed on-chain payment. Re-storing bytes
        # carries the existing value forward and cannot raise it.
        t = float((blob_meta.get(cid) or {}).get('tips', 0))
        _db.execute('INSERT OR REPLACE INTO blob (cid,b64,size,last,tips) VALUES (?,?,?,?,?)',
                    (cid, b64, len(b64 or ''), now, t))
        blob_meta[cid] = {'size': len(b64 or ''), 'last': now, 'tips': t,
                          'reports': sum(_blob_reporters.get(cid, {}).values())}   # carry existing report weight
        _evict_locked()
        _db.commit()
        return True

def blob_report(cid, account, rep):
    # a signed, reputation-WEIGHTED community report referencing this media: a NEGATIVE term in
    # blob_score, and a hard PRIORITY TAKEDOWN (delete now, ignore the cap) once the weighted sum of
    # distinct reporters crosses TAKEDOWN_WEIGHT — unless the content is paid-pinned. Weighting by
    # account_rep is what stops a pile of empty throwaway accounts from forcing a takedown.
    if not cid or rep <= 0:
        return
    with _blob_lock:
        s = _blob_reporters.setdefault(cid, {}); s[account] = rep     # dedupe by account, keep its weight
        w = sum(s.values())
        m = blob_meta.get(cid)
        if m:
            m['reports'] = w
        if m and w >= TAKEDOWN_WEIGHT and pinned.get(cid, 0) <= time.time():
            _db.execute('DELETE FROM blob WHERE cid=?', (cid,)); _db.commit()
            blob_meta.pop(cid, None)

def blob_touch(cid):                 # a read counts as use; RAM-only (avoids a write per read)
    m = blob_meta.get(cid)
    if m:
        m['last'] = time.time()

def _shard_relays():
    # Identities eligible to hold a share: us, plus every peer that has proved an identity. URL-only
    # (legacy) peers can't be placed against, so they simply don't participate in placement.
    out = [ID_ACCT] if ID_ACCT else []
    out.extend(peers_by_acct.keys())
    return out

def _responsible(cid, accts=None):
    # RENDEZVOUS ("highest random weight") HASHING. Every relay independently computes the same
    # ranking of relays for a given cid and keeps it only if it lands in the top BLOB_REPLICAS. No
    # coordinator, no directory, no agreement protocol — just a hash — which is the only kind of
    # placement that fits a network where anyone can join and nobody is in charge.
    #
    # This exists because the old policy was BOTH wasteful and lossy: the node pushes every blob to
    # every relay, and eviction ranked by blob_score, which is identical everywhere — so all relays
    # evicted the SAME victims at the same time. Popular media sat on N relays while unpopular media
    # dropped to zero copies network-wide. Placement fixes both ends: ~BLOB_REPLICAS copies of
    # everything instead of N copies of some things and none of the rest.
    accts = accts if accts is not None else _shard_relays()
    if not ID_ACCT or len(accts) <= BLOB_REPLICAS:
        return True                                          # small network: everyone holds everything
    def weight(a):
        return hashlib.blake2b((cid + '|' + a).encode(), digest_size=8).digest()
    mine = weight(ID_ACCT)
    ahead = 0
    for a in accts:
        if a != ID_ACCT and weight(a) > mine:
            ahead += 1
            if ahead >= BLOB_REPLICAS:
                return False
    return True

def _evict_locked():                 # called with _blob_lock held; drops least-valuable unpinned first
    total = _blob_total()
    if total <= BLOB_CAP:
        return
    now = time.time()
    accts = _shard_relays()
    # Evict what we are NOT responsible for before anything we are: an opportunistic copy of a popular
    # post is the cheapest thing in the cache to lose (several other relays hold it by construction),
    # while our own share may be one of only BLOB_REPLICAS copies in existence. Nothing is deleted
    # that the cap wasn't already going to delete — this only chooses better victims.
    victims = sorted((1 if _responsible(c, accts) else 0, blob_score(m), m['last'], c)
                     for c, m in blob_meta.items() if pinned.get(c, 0) <= now)
    victims = [(s, l, c) for _r, s, l, c in victims]
    for _score, _last, c in victims:
        if total <= BLOB_CAP:
            break
        total -= blob_meta[c]['size']
        _db.execute('DELETE FROM blob WHERE cid=?', (c,))
        blob_meta.pop(c, None)

def blob_load_meta():                # startup: rebuild the small RAM index from the SQLite table
    with _blob_lock:
        for cid, size, last, tips in _db.execute('SELECT cid,size,last,tips FROM blob'):
            blob_meta[cid] = {'size': size, 'last': last, 'tips': tips or 0.0, 'reports': 0.0}

# In WAL mode every put/evict appends frames to blobs.db-wal; SQLite only folds them back into the
# main db on a checkpoint. Under steady write traffic the auto-checkpoint (default 1000 pages) can
# lag, letting the -wal file grow into the tens of MB — bloating the disk footprint and slowing
# restart recovery. A periodic TRUNCATE checkpoint folds the log back in and shrinks -wal to zero.
# It runs under _blob_lock (the single serialiser for this connection) so it can't race a writer,
# and every failure is swallowed: a checkpoint is best-effort housekeeping, never worth a crash.
WAL_CHECKPOINT_S = float(os.environ.get('XC_WAL_CHECKPOINT_S', '300'))   # 0/negative disables the routine

def _wal_checkpoint():
    while True:
        time.sleep(WAL_CHECKPOINT_S)
        try:
            with _blob_lock:
                _db.execute('PRAGMA wal_checkpoint(TRUNCATE)')
        except Exception:
            pass                         # busy/locked/etc — just try again next tick

if WAL_CHECKPOINT_S > 0:
    threading.Thread(target=_wal_checkpoint, daemon=True).start()

def ensure_release_blob(cid):
    # A signed release (an app update) is CRITICAL INFRA — every relay must hold it, independent of tips
    # or the value-ranked sync budget. So: PIN it (never evict), and if we don't already have the bytes,
    # pull them from a peer relay that does. Runs in a background thread (a 20 MB pull mustn't block a
    # request). This is what makes an update propagate to the whole relay set on its own.
    if not cid:
        return
    pinned[cid] = time.time() + 3650 * 86400          # ~never; releases are few (capped per publisher) and small
    if blob_has(cid):
        return
    for r in list(known):
        if r == SELF or '127.0.0.1' in r or 'localhost' in r:
            continue                                   # a peer, not ourselves/loopback (we're here BECAUSE we lack it)
        try:
            d = json.loads(urllib.request.urlopen(r + '/blob?cid=' + cid, timeout=90).read())
            if d.get('b64'):
                blob_put(cid, d['b64'])
                return
        except Exception:
            pass

def _release_pin_cids():
    # the cids whose BYTES we keep pinned: the newest RELEASE_PIN_KEEP records per publisher (the list is
    # append-ordered, newest last). KEEP<=0 pins nothing extra (records/signatures are unaffected either way).
    keep = set()
    if RELEASE_PIN_KEEP <= 0:
        return keep
    for _pub, lst in releases.items():
        if isinstance(lst, list):
            for rec in lst[-RELEASE_PIN_KEEP:]:
                c = (rec or {}).get('cid')
                if c:
                    keep.add(c)
    return keep

def reconcile_release_pins():
    # Enforce the newest-N pin window: UNPIN any older release cid so its bytes become evictable under
    # disk pressure (the record stays; the bytes are re-fetchable from IPFS/peers). Never touches a
    # PAID pin (pins_paid) — a user who paid to keep a cid owns that pin regardless of release status.
    keep = _release_pin_cids()
    paid = set(pins_paid.values())
    for _pub, lst in list(releases.items()):
        if not isinstance(lst, list):
            continue
        for rec in lst:
            c = (rec or {}).get('cid')
            if c and c not in keep and c not in paid and pinned.get(c):
                pinned.pop(c, None)          # release pin lifted; falls back to normal cache eviction
    return keep

def sync_release_blobs():
    # on startup (and after gossip), make sure we hold the newest releases' bytes — catches a relay that
    # was down when a release was published — while lifting stale pins on releases past the keep window.
    time.sleep(1.0)
    keep = reconcile_release_pins()
    mark_dirty()                                       # persist any pins we just lifted (pinned is in the store)
    for _pub, recs in list(releases.items()):
        for rec in recs:
            if (rec or {}).get('cid') in keep:
                ensure_release_blob(rec.get('cid'))

# Release records are verified against BOTH preimages during the migration (issue #7). This one is
# the load-bearing case: every release already published is legacy-signed, so a verifier that took
# only v2 would reject the app's own update record and break self-delivery for existing installs.
def _release_verify(m, pub, sig):
    if xc is None:
        return False
    return xc.verify_either(pub, sig, xc.release_canon(m), xc.release_canon_legacy(m))

def accept_release(m):
    # Ingest a signed release record — VERIFYING it, unlike other relay writes. Releases are app
    # updates, so a forged flood here isn't inert junk: the old code stored any record and capped the
    # list at 24, which let an attacker push ≥24 forged records under the pinned publisher's key and
    # EVICT the genuine one, freezing updates network-wide (a suppression attack). Now the relay checks
    # the publisher-pinned signature at the door and drops anything that doesn't validate, so forged
    # records never enter, the list stays genuine, and the per-cid pin + background pull can't be
    # amplified by junk. Returns True if newly stored.
    if xc is None:
        return False
    pub_acc = m.get('publisher', '')
    pub, sig = m.get('pub', ''), m.get('sig', '')
    if pub_acc != PUBLISHER_ACCT:                      # only the pinned publisher's channel is stored
        return False
    try:
        signer = xc.pub_to_addr(pub)
        gone, successor = revoked_publisher(signer)
        if gone:
            return False                 # this key was revoked by the offline root — never install it
        allowed = (signer == PUBLISHER_ACCT) or bool(successor_of_pinned() == signer)
        if not allowed or not _release_verify(m, pub, sig):
            return False
    except Exception:
        return False
    lst = releases.setdefault(pub_acc, [])
    if any(x.get('sig') == sig for x in lst):
        return False
    lst.append(m)
    releases[pub_acc] = lst[-24:]
    _cap_dict(releases, RELEASE_PUBS_MAX)
    keep = reconcile_release_pins()                    # this release just became newest -> older one may drop out
    if m.get('cid') and m['cid'] in keep:              # only pin+pull bytes if it's inside the keep window
        threading.Thread(target=ensure_release_blob, args=(m['cid'],), daemon=True).start()
    mark_dirty()
    return True

def backfill():
    # SYNC ON JOIN. bootstrap() learns the peer list but pulls no content, so a freshly launched
    # relay used to come up blank and only accumulate what was pushed to it AFTER joining — it never
    # mirrored the existing feed. Here a joining relay PULLS the current state from its peers so it
    # catches up to the network. Heads (the feed) and signed release records (app updates) are the
    # load-bearing state and both have bulk GETs; the relay verifies neither (clients/node do — same
    # trust model as /push), so a peer can only fail to serve, never forge what we store.
    time.sleep(1.5)                                   # let bootstrap() populate `known` first
    peers = [r for r in list(known)
             if r != SELF and '127.0.0.1' not in r and 'localhost' not in r]
    # --- heads: newest-wins merge, identical rule to /push ---
    for r in peers:
        try:
            d = json.loads(urllib.request.urlopen(r + '/heads', timeout=8).read())
        except Exception:
            continue
        with _heads_lock:
            for h in d.get('heads', []):
                a = h.get('author')
                if not a:
                    continue
                cur = heads.get(a)
                if cur is None and len(heads) >= MAX_HEADS:
                    heads.pop(min(heads, key=lambda x: head_score(x, heads[x])), None)
                    cur = None
                if cur is None or h.get('seq', 0) > cur.get('seq', 0) \
                        or h.get('expires', 0) > cur.get('expires', 0):
                    heads[a] = h
    # --- releases: dedup by sig, then pull + pin each release's bytes so we can serve updates ---
    for r in peers:
        try:
            d = json.loads(urllib.request.urlopen(r + '/releases?pub=' + PUBLISHER_ACCT, timeout=8).read())
        except Exception:
            continue
        for m in d.get('records', []):
            accept_release(m)                         # verify (publisher-pinned sig) + store + pull bytes
    mark_dirty()                                      # persist the caught-up state

def grant_pin(cid, payhash):
    # PAY-TO-PIN: verify payhash is a confirmed Nano send TO this relay's account, then protect cid
    # from eviction for a span proportional to the amount. A public ledger read — no key needed, the
    # relay never moves funds; the PINNER paid. Each payment is consumed once (no double-claim).
    if xc is None or not RELAY_ACCT or not cid or not payhash or payhash in pins_paid:
        return 0
    try:
        bi = xc.rpc({'action': 'block_info', 'json_block': 'true', 'hash': payhash})
        c = bi.get('contents', {})
        to_us = (c.get('link_as_account') == RELAY_ACCT
                 or c.get('link', '').upper() == xc.nano_to_pub(RELAY_ACCT).upper())
        amt = int(bi.get('amount', '0'))
        confirmed = str(bi.get('confirmed', '')).lower() == 'true'
        subtype = str(bi.get('subtype', '')).lower()
    except Exception:
        return 0
    # CONFIRMED ONLY. A block can be in the ledger without being cemented, and an unconfirmed block may
    # still be rolled back — so granting pin time on one lets storage be bought with a payment that
    # never lands. This FAILS CLOSED: anything other than an explicit 'true' buys nothing, including an
    # RPC that omits the field entirely. (The endpoint's own 402 text always claimed "confirmed"; the
    # check was simply missing.)
    if not confirmed:
        if 'confirmed' not in bi:
            # An operator problem, not a payer problem, and otherwise indistinguishable: an RPC that
            # never reports confirmation silently disables paid pins on this relay. Say so once per
            # attempt rather than rejecting in silence.
            print(f'pay-to-pin: RPC gave no confirmation status for {payhash[:12]}… — no pin granted '
                  f'(is XC_NANO_RPC a full node?)', flush=True)
        return 0
    # Defence in depth: `amount` and `link` only mean "paid us" on a SEND. Read off a receive or epoch
    # block they describe something else entirely. Tolerated when absent, since not every proxy returns
    # subtype and the link/amount checks below still have to pass.
    if subtype and subtype != 'send':
        return 0
    if not to_us or amt <= 0:
        return 0
    pins_paid[payhash] = cid
    exp = max(pinned.get(cid, 0.0), time.time()) + amt * _PIN_S_PER_RAW
    pinned[cid] = exp
    mark_dirty()                         # persisted by the autosave within ≤5s (no per-write flush)
    return exp

def blob_credit(cid, payhash):
    # The ONLY way a blob gains value. A tip is an on-chain send, so it can be verified exactly like a
    # pay-to-pin payment: confirmed, a send, and not to the sender's own account. The amount is read
    # from the LEDGER, never from the caller, and each payment is consumed once — so "this content is
    # valued" becomes a claim backed by money that actually moved, instead of a number in a POST body.
    #
    # Residual, stated plainly: Nano is feeless, so an attacker with two accounts can still send to
    # themselves and credit their own content for free. That is bounded and traceable rather than
    # costless and anonymous, and the real fix is to weight credited value by the SENDER's on-chain
    # reputation — the same Sybil-resistant signal head_score and the report weighting already use.
    if xc is None or not cid or not payhash or payhash in tips_paid:
        return 0.0
    try:
        bi = xc.rpc({'action': 'block_info', 'json_block': 'true', 'hash': payhash})
        c = bi.get('contents', {})
        amt = int(bi.get('amount', '0'))
        confirmed = str(bi.get('confirmed', '')).lower() == 'true'
        subtype = str(bi.get('subtype', '')).lower()
        src = c.get('account', '')
        dst = c.get('link_as_account', '')
    except Exception:
        return 0.0
    if not confirmed or (subtype and subtype != 'send') or amt <= 0:
        return 0.0
    if not dst or dst == src:                       # a self-send buys nothing
        return 0.0
    # WEIGHTED BY THE SENDER'S ON-CHAIN REPUTATION (issue #11). Verification alone bounds the attack
    # but does not price it: Nano is feeless, so two accounts you own can send to each other for free.
    # account_rep is 0 for a fresh throwaway and rises with balance, chain height and recent activity —
    # the same Sybil-resistant signal head_score and the report weighting already use. So self-dealing
    # from disposable accounts credits ~nothing, while a tip from an established account counts fully.
    try:
        weight = float(xc.account_rep(src))
    except Exception:
        weight = 0.0
    credited = amt * max(0.0, min(1.0, weight))
    tips_paid[payhash] = cid
    if credited <= 0:
        return 0.0                       # consumed (so it can't be retried) but worth nothing
    with _blob_lock:
        m = blob_meta.get(cid)
        if m is not None:
            m['tips'] = float(m.get('tips', 0)) + credited
            _db.execute('UPDATE blob SET tips=? WHERE cid=?', (m['tips'], cid))
            _db.commit()
    mark_dirty()
    return float(credited)

# --- persistence: the WHOLE relay state survives a restart, not just heads ---
# (in-memory before this meant comments, uploaded media, likes, poll votes vanished on restart)
_STATE_KEYS = ('engage', 'notifs', 'supporters', 'follows', 'comments',   # blobs now live in SQLite
               'releases', 'profiles', 'dmkeys', 'dms', 'pollvotes', 'reports', 'pinned', 'pins_paid',
               'tips_paid', 'revocations')

def _prune_loaded():
    # PRUNE-ON-LOAD. The per-table caps in the write handlers only bound NEW writes; state loaded from
    # disk is not capped on the way in, so a store that grew large under older (uncapped) code would
    # re-inflate RAM on every restart (this is what tipped the 512 MB node into an OOM on redeploy).
    # Applying the same ceilings here means the in-memory footprint is bounded by the caps regardless
    # of how big the file on disk got, and the next save() writes the smaller state back. (heads is left
    # to prune()/head_score, which trims it by on-chain value rather than insertion order.)
    _cap_dict(notifs, NOTIF_ACCTS)
    for a, lst in list(notifs.items()):
        if isinstance(lst, list) and len(lst) > NOTIF_MAX:
            notifs[a] = lst[-NOTIF_MAX:]
    _cap_dict(supporters, SUPPORTERS_MAX)
    _cap_dict(follows, FOLLOWS_MAX)
    for a, rec in list(follows.items()):
        fl = (rec or {}).get('follows')
        if isinstance(fl, list) and len(fl) > FOLLOW_LIST_MAX:
            rec['follows'] = fl[:FOLLOW_LIST_MAX]
    _cap_dict(profiles, PROFILES_MAX)
    _cap_dict(dmkeys, DMKEYS_MAX)
    _cap_dict(comments, COMMENT_POSTS_MAX)
    for pid, lst in list(comments.items()):
        if isinstance(lst, list) and len(lst) > COMMENTS_PER_POST:
            comments[pid] = lst[-COMMENTS_PER_POST:]
    _cap_dict(pollvotes, POLLS_MAX)
    for pid, votes in list(pollvotes.items()):
        if isinstance(votes, dict):
            _cap_dict(votes, POLL_VOTERS_MAX)
    _cap_dict(engage, ENGAGE_MAX)
    for pid, e in list(engage.items()):
        rs = (e or {}).get('resharers')
        if isinstance(rs, list) and len(rs) > RESHARERS_MAX:
            e['resharers'] = rs[:RESHARERS_MAX]
    _cap_dict(reports, REPORT_POSTS)
    for pid, recs in list(reports.items()):
        if isinstance(recs, dict):
            _cap_dict(recs, REPORT_PER_POST)
    _cap_dict(releases, RELEASE_PUBS_MAX)
    for pub, lst in list(releases.items()):
        if isinstance(lst, list) and len(lst) > 24:
            releases[pub] = lst[-24:]
    if len(dms) > DM_MAX:
        del dms[:-DM_MAX]

def load_state():
    global heads
    if not os.path.exists(STORE):
        return
    try:
        d = json.load(open(STORE))
        if isinstance(d, list):                      # legacy format: a bare list of heads
            heads = {h['author']: h for h in d}
            return
        heads = {h['author']: h for h in d.get('heads', [])}
        for k in _STATE_KEYS:
            v = d.get(k)
            g = globals()[k]                          # freshly-empty dict/list at import time
            if isinstance(g, dict) and isinstance(v, dict):
                g.update(v)
            elif isinstance(g, list) and isinstance(v, list):
                g.extend(v)
        for cid, b64 in (d.get('blobs') or {}).items():   # one-time migration: legacy in-JSON blobs -> SQLite
            if b64:
                blob_put(cid, b64)
        _prune_loaded()                              # bound the loaded state to the same caps as live writes
        mark_dirty()                                 # so the pruned (smaller) state is written back on next save
    except Exception:
        pass

def save():
    # atomic write of the full state (heads + everything else)
    state = {'heads': list(heads.values())}
    for k in _STATE_KEYS:
        state[k] = globals()[k]
    tmp = STORE + '.tmp'
    try:
        json.dump(state, open(tmp, 'w'))
        os.replace(tmp, STORE)
    except Exception:
        pass

